"""Write Nav2 params for the H3 set-ups from the stock nav2_bringup params.

The baseline and prediction files are identical except that the prediction layer
is enabled in one, so plain Nav2 and Nav2 + prediction run with exactly the same
planner, controller and costmap settings. The social file adds limits fitted to
the human driver in THÖR-MAGNI (p95 speed 0.47 m/s, p95 |acceleration| 0.40 m/s²,
see experiments/human_reference.py) on top of the prediction file. Run inside the container:
  python3 experiments/make_nav2_params.py ros2_ws/src/social_nav_sim/config
"""
import sys
from pathlib import Path

import yaml
from ament_index_python.packages import get_package_share_directory

HUMAN_V_MAX = 0.47
HUMAN_ACCEL = 0.40
LAYER = {'plugin': 'social_nav_layers::PredictionLayer', 'topic': '/predicted_people',
         'radius': 0.45, 'max_cost': 200, 'max_age': 1.0}


def main():
    out = Path(sys.argv[1])
    stock = Path(get_package_share_directory('nav2_bringup')) / 'params' / 'nav2_params.yaml'
    for name, enabled in (('nav2_params_baseline.yaml', False), ('nav2_params_prediction.yaml', True),
                          ('nav2_params_social.yaml', True)):
        p = yaml.safe_load(stock.read_text())
        for cm in ('local_costmap', 'global_costmap'):
            params = p[cm][cm]['ros__parameters']
            params['plugins'] = params['plugins'] + ['prediction_layer']
            params['prediction_layer'] = dict(LAYER, enabled=enabled)
        p['global_costmap']['global_costmap']['ros__parameters']['update_frequency'] = 2.5
        if name == 'nav2_params_social.yaml':
            mppi = p['controller_server']['ros__parameters']['FollowPath']
            mppi['vx_max'] = HUMAN_V_MAX
            smoother = p['velocity_smoother']['ros__parameters']
            smoother['max_velocity'] = [HUMAN_V_MAX, 0.0, 1.0]
            smoother['min_velocity'] = [-0.2, 0.0, -1.0]
            smoother['max_accel'] = [HUMAN_ACCEL, 0.0, 1.5]
            smoother['max_decel'] = [-2 * HUMAN_ACCEL, 0.0, -1.5]
        if (out / name).exists() and '--all' not in sys.argv and name != 'nav2_params_social.yaml':
            continue
        (out / name).write_text('# generated by experiments/make_nav2_params.py from nav2_bringup defaults\n'
                                + yaml.safe_dump(p, sort_keys=False))
        print('wrote', out / name)


if __name__ == '__main__':
    main()
